"use strict";

/**
 * Phase 4 (#713): the frozen transcript is a self-contained HTML file.
 * The stylesheet is the forge token build, fonts inlined, and a missing
 * or external bundle refuses to write. The console viewer uses the same
 * empty / missing / blocked copy.
 */

const { describe, it, after } = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");

const { loadDb } = require("./helpers/env");
const { cleanup } = loadDb();

const { contentSecurityPolicy } = require("../src/web/middleware/csp");
const {
  EXPORT_CSS_PATH,
  loadTranscriptExportCss,
  transcriptExportCss,
} = require("../src/web/assets/transcriptExportCss");
const {
  renderTranscriptHtml,
  renderAttachmentsHtml,
} = require("../src/features/tickets/transcript");
const consoleView = require("../src/web/views/transcripts/transcriptPage");

after(cleanup);

const EXTERNAL_URL = /url\(\s*['"]?(?:https?:|\/|\.\.)/i;

describe("transcript export CSS (#713)", () => {
  it("inlines the forge token bundle and no external file", () => {
    const css = transcriptExportCss();
    assert.equal(css, loadTranscriptExportCss());
    assert.equal(transcriptExportCss(), css, "the process caches the file");
    assert.ok(css.includes("#101318"));
    assert.ok(css.includes("#29a8bd"));
    assert.match(css, /data:font\/woff2|data:application\/font-woff/);
    assert.doesNotMatch(css, EXTERNAL_URL);
    assert.ok(fs.existsSync(EXPORT_CSS_PATH));
  });

  it("refuses a missing, untokened, or externally linked stylesheet", () => {
    const dir = fs.mkdtempSync(path.join(os.tmpdir(), "txcss-"));
    const missing = path.join(dir, "nope.css");
    assert.throws(
      () => loadTranscriptExportCss(missing),
      (err) =>
        err.code === "TRANSCRIPT_EXPORT_CSS_MISSING" &&
        /Refusing to write/.test(err.message)
    );

    const plain = path.join(dir, "plain.css");
    fs.writeFileSync(plain, "body{color:red}\n");
    assert.throws(
      () => loadTranscriptExportCss(plain),
      (err) =>
        err.code === "TRANSCRIPT_EXPORT_CSS_MISSING" &&
        /not the forge token bundle/.test(err.message)
    );

    const external = path.join(dir, "ext.css");
    fs.writeFileSync(
      external,
      "body{background:#101318;color:#29a8bd} @font-face{src:url(https://cdn.example/a.woff2)}"
    );
    assert.throws(
      () => loadTranscriptExportCss(external),
      (err) =>
        err.code === "TRANSCRIPT_EXPORT_CSS_MISSING" &&
        /external file/.test(err.message)
    );

    const styleBreak = path.join(dir, "break.css");
    fs.writeFileSync(
      styleBreak,
      "/* </style> */ body{background:#101318;color:#29a8bd}\n"
    );
    const safe = loadTranscriptExportCss(styleBreak);
    assert.ok(!safe.toLowerCase().includes("</style"));
    assert.match(safe, /<\\\/style/);
    fs.rmSync(dir, { recursive: true, force: true });
  });
});

describe("renderTranscriptHtml offline document (#713)", () => {
  const ticket = {
    community_id: 1,
    ticket_number: 9,
    creator_user_id: "u1",
    created_at: 1,
    closed_at: 2,
    is_sensitive: 0,
    reason: "help",
  };

  it("inlines CSS, keeps the archive contract, and has no network stylesheet", () => {
    const html = renderTranscriptHtml(ticket, [], { requesterLabel: "Alice" });
    assert.match(html, /Requester<\/dt><dd>Alice/);
    assert.match(html, /<p class="empty-state">No messages archived\.<\/p>/);
    assert.match(html, /Generated by Boiler Snake · do not share publicly/);
    assert.ok(html.includes("#101318"));
    assert.ok(html.includes("#29a8bd"));
    assert.match(html, /data:font\/woff2|data:application\/font-woff/);
    assert.ok(!/<link\b/i.test(html), "no external stylesheet");
    assert.ok(!/<script\b/i.test(html), "the export does not load a script");
    assert.doesNotMatch(html, EXTERNAL_URL);
    assert.ok(!html.includes("summary-prose"), "the frozen file has no AI summary");
    assert.ok(!html.includes("sl-copy-button"));
  });

  it("states a missing file and a blocked scheme", () => {
    const html = renderAttachmentsHtml([
      { name: "notes.txt" },
      { name: "x.png", href: "javascript:alert(1)" },
    ]);
    assert.match(html, /\(file missing from the archive\)/);
    assert.match(html, /\(link scheme blocked\)/);
    assert.ok(!/href="javascript/i.test(html));
    assert.ok(!/src="javascript/i.test(html));
  });
});

describe("transcript viewer edge states (#713)", () => {
  it("uses the shared empty state, panels, and the same attachment copy", () => {
    const attachments = String(
      consoleView.renderAttachments({
        attachment_urls: JSON.stringify([
          { name: "notes.txt" },
          { name: "x.png", href: "javascript:alert(1)" },
        ]),
      })
    );
    assert.match(attachments, /\(file missing from the archive\)/);
    assert.match(attachments, /link scheme blocked/);
    assert.ok(!/href="javascript/i.test(attachments));

    const page = String(
      consoleView.renderTranscriptPage({
        req: { user: { userId: "42", discordTag: "ada" }, csrfToken: "t" },
        res: { locals: { cspNonce: "n" } },
        ticket: {
          community_id: "100",
          ticket_number: 3,
          transcript_token: "aaaaaaaa-bbbb-4ccc-8ddd-eeeeeeeeeeee",
          creator_user_id: "100000000000000042",
          created_at: 1,
          closed_at: 2,
          reason: "help",
        },
        messages: [],
        summary: null,
        staff: true,
        tier: "staff",
        names: new Map(),
        guilds: [{ id: "900", communityId: "100", name: "Forge Guild" }],
      })
    );
    assert.match(page, /class="empty-state"/);
    assert.match(page, /No messages were archived for this ticket/);
    assert.match(page, /class="bs-panel transcript-header"/);
    assert.match(page, /class="bs-kv"/);
    assert.ok(!page.includes('class="panel transcript-header"'));
  });

  it("keeps transcript rules in primitives and does not ship styles.css", () => {
    assert.equal(
      fs.existsSync(path.join(__dirname, "../src/web/public/styles.css")),
      false
    );
    const css = fs.readFileSync(
      path.join(__dirname, "../src/web/assets/page.css"),
      "utf8"
    );
    assert.doesNotMatch(css, /\.tmsg\b/);
    const primitives = fs.readFileSync(
      path.join(__dirname, "../src/web/assets/primitives.css"),
      "utf8"
    );
    assert.match(primitives, /\.tmsg\b/);
    assert.match(primitives, /font-family:\s*var\(--bs-font-sans\)/);
  });
});

describe("contentSecurityPolicy font-src (#713)", () => {
  it("adds font-src data only when the raw export asks for it", () => {
    const shell = contentSecurityPolicy("abc");
    assert.match(shell, /default-src 'self'/);
    assert.match(shell, /style-src 'self' 'unsafe-inline'/);
    assert.doesNotMatch(shell, /font-src/);
    const raw = contentSecurityPolicy("abc", { embedFonts: true });
    assert.match(raw, /font-src 'self' data:/);
    assert.match(raw, /script-src 'self' 'nonce-abc'/);
  });
});
